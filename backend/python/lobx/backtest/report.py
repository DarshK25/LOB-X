"""Markdown summary of research results (results/research/*.json)."""
from __future__ import annotations

import json
from pathlib import Path


def _f(x, nd=2, signed=False):
    if x is None:
        return "-"
    return f"{x:+.{nd}f}" if signed else f"{x:.{nd}f}"


def _window_md(res: dict) -> list[str]:
    c = res["calibration"]
    arr, hk, fv = c["arrival"], c["hawkes"], c["fair_value"]
    out = [
        f"## {res['window']}",
        "",
        f"Venue: {res['venue']}. In-sample {c['hours']:.1f} h, out-of-sample "
        f"{res['oos_hours']:.1f} h. Quantity 0.001 BTC per quote, position limit 0.01 BTC.",
        "",
        "| Calibrated (in-sample) | Value |",
        "|---|---|",
        f"| sigma | {c['sigma']:.3f} USD/sqrt(s) ({c['sigma_bps_per_sqrt_s']:.3f} bp/sqrt(s)); "
        f"out-of-sample realised {res['oos_sigma']:.3f} |",
        f"| arrival A, k | {arr['A']:.3f} /s, {arr['k']:.3f} /USD (R2 {arr['r2']:.2f}, "
        f"{arr['market_orders']:,} market orders) |",
        f"| Hawkes buy mu / alpha / beta / n | {hk['buy']['mu']:.3f} / {hk['buy']['alpha']:.3f} / "
        f"{hk['buy']['beta']:.3f} / {hk['buy']['branching_ratio']:.2f} |",
        f"| Hawkes sell mu / alpha / beta / n | {hk['sell']['mu']:.3f} / {hk['sell']['alpha']:.3f} / "
        f"{hk['sell']['beta']:.3f} / {hk['sell']['branching_ratio']:.2f} |",
        f"| fair value (2 s mid change) | b_flow {fv['b_flow']:.3f}, b_obi {fv['b_obi']:.3f}; "
        f"R2 in-sample {fv['r2_in_sample']:.3f}, out-of-sample {fv.get('r2_out_of_sample', 0):.3f} |",
        "",
    ]
    for fee, block in res["fees"].items():
        boot = block["bootstrap"]
        out += [
            f"### {block['profile']['label']}",
            "",
            f"Gamma chosen in-sample (best net PnL with >= 100 fills/h): "
            f"AS {block['tuning']['AS']:g}, "
            f"GLFT {block['tuning']['GLFT']:g} (1/USD).",
            "",
            "| Strategy | Net PnL $ | 95% CI | Sharpe | Max DD $ | Fills/h | Edge/fill $ | "
            "Adverse 5s bp | Break-even maker bp | P(beats FixedSpread) |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for r in block["oos"]:
            b = boot.get(r["strategy"], {})
            ci = b.get("pnl_ci")
            out.append(
                f"| {r['strategy']} | {_f(r['net_pnl'], 3, True)} | "
                f"{'[' + _f(ci[0], 2, True) + ', ' + _f(ci[1], 2, True) + ']' if ci else '-'} | "
                f"{_f(r['sharpe'], 1, True)} | {_f(r['max_drawdown'], 3)} | "
                f"{_f(r['fills_per_hour'], 0)} | {_f(r['edge_per_fill_usd'], 5, True)} | "
                f"{_f(r['adverse_bps'], 2, True)} | {_f(r['breakeven_maker_fee_bps'], 2, True)} | "
                f"{_f(b.get('p_better_than_baseline'), 2)} |")
        out += ["", "Stress tests (GLFT+Hawkes+FV unless named):", "",
                "| Variant | Net PnL $ | Fills/h | Adverse 5s bp |", "|---|---|---|---|"]
        for r in block["stress"]:
            out.append(f"| {r['strategy'].removeprefix('stress: ')} | "
                       f"{_f(r['net_pnl'], 3, True)} | {_f(r['fills_per_hour'], 0)} | "
                       f"{_f(r['adverse_bps'], 2, True)} |")
        out.append("")
    return out


def write_summary(results_dir: str | Path) -> Path:
    d = Path(results_dir)
    d.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Research results",
        "",
        "Generated by `scripts/run_research.py`. Every number below is out-of-sample: models",
        "are calibrated and gamma is chosen on the in-sample part only. Confidence intervals",
        "are 95% moving-block bootstrap intervals on per-minute PnL (10-minute blocks).",
        "Sharpe is annualised from 1-minute PnL and is not meaningful over a few hours except",
        "as a ranking; the bootstrap intervals are the comparison that matters.",
        "",
    ]
    for path in sorted(d.glob("*.json")):
        lines += _window_md(json.loads(path.read_text()))
    out = d / "SUMMARY.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out
